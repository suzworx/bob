// Bob Cardputer v2 — CA root bundle generator.
//
// Reads every *.pem in apps/cardputer/ca-roots (sorted by filename), validates
// each with node:crypto, and writes apps/cardputer/include/ca_roots.h
// containing:
//   - a header comment listing each root's subject CN, SHA-256 fingerprint
//     (computed over the DER, `fingerprint256`) and validTo;
//   - `static const char kCaRoots[] PROGMEM = ...;` built programmatically from
//     the file contents, with each PEM line emitted as its own C string literal
//     ending in a newline escape.
//
// The header is always produced by RUNNING this script — never hand-typed, so
// the embedded bytes are byte-for-byte the official roots from
// letsencrypt.org / pki.goog. `--check` regenerates in memory and exits 1 if
// ca_roots.h differs (used to fail CI when a root rotates or drifts).

import { X509Certificate, createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP_DIR = join(HERE, '..');
const CA_DIR = join(APP_DIR, 'ca-roots');
const OUT = join(APP_DIR, 'include', 'ca_roots.h');

// Node's node:crypto X509Certificate exposes the DER as `raw`. Fingerprint is
// sha256 over the DER; rendered uppercase, colon-separated.
function fingerprint(cert) {
  return createHash('sha256').update(cert.raw).digest('hex').toUpperCase().match(/.{2}/g).join(':');
}

// node:crypto exposes subject as a string like "C=US\nO=...,\nCN=GTS Root R1".
// Flatten newlines so it renders as one comment line.
function commonName(cert) {
  const m = cert.subject.match(/(?:^|\n)CN=([^\n,]+)/);
  return m ? m[1].trim().replace(/\s+/g, ' ') : cert.subject.replace(/\n/g, ' ');
}

function readRoots() {
  if (!existsSync(CA_DIR)) {
    throw new Error(`ca-roots dir not found: ${CA_DIR}`);
  }
  const files = readdirSync(CA_DIR)
    .filter((f) => f.endsWith('.pem'))
    .sort();
  if (files.length === 0) {
    throw new Error(`no *.pem found in ${CA_DIR}`);
  }
  const roots = [];
  for (const f of files) {
    // Normalise CRLF so the embedded bytes are identical on every platform.
    const pem = readFileSync(join(CA_DIR, f), 'utf8').replace(/\r\n?/g, '\n').trim() + '\n';
    let cert;
    try {
      cert = new X509Certificate(pem);
    } catch (e) {
      throw new Error(`invalid certificate ${f}: ${e.message}`);
    }
    roots.push({ file: f, pem, cert });
  }
  return roots;
}

function render(roots) {
  const lines = [];
  lines.push('// Bob Cardputer v2 — CA root bundle, GENERATED by scripts/gen-ca-roots.mjs.');
  lines.push('// Do not edit by hand; regenerate with `node scripts/gen-ca-roots.mjs`.');
  lines.push('// Root certificates (subject CN / SHA-256 fingerprint / validTo):');
  for (const { file, cert } of roots) {
    lines.push(
      `//   ${file}: CN=${commonName(cert)}, ` +
        `fp256=${fingerprint(cert)}, validTo=${cert.validTo}`
    );
  }
  lines.push('#pragma once');
  lines.push('');
  lines.push('static const char kCaRoots[] PROGMEM =');
  for (const { pem } of roots) {
    for (const line of pem.split('\n')) {
      if (line.length === 0) continue; // PEM already carries its own \n per line
      lines.push(`    "${line}\\n"`);
    }
  }
  lines.push('    "";');
  lines.push('');
  return lines.join('\n');
}

// process.argv: [node, script, args...] on this Node; the first real arg is [2].
const check = process.argv[2] === '--check';

const roots = readRoots();
const generated = render(roots);

if (check) {
  let current = '';
  // Normalise CRLF (git core.autocrlf converts the checked-out header on
  // Windows) so --check is byte-deterministic across platforms; only genuine
  // content drift fails the gate.
  if (existsSync(OUT)) current = readFileSync(OUT, 'utf8').replace(/\r\n?/g, '\n');
  if (current !== generated) {
    console.error('ca_roots.h is out of date or missing; run `node scripts/gen-ca-roots.mjs`.');
    process.exit(1);
  }
  console.log('ca_roots.h is up to date.');
  for (const { file, cert } of roots) {
    console.log(`${file}: ${commonName(cert)} ${fingerprint(cert)} ${cert.validTo}`);
  }
  process.exit(0);
}

writeFileSync(OUT, generated);
console.log(`wrote ${OUT}`);
for (const { file, cert } of roots) {
  console.log(`${file}: ${commonName(cert)} ${fingerprint(cert)} ${cert.validTo}`);
}