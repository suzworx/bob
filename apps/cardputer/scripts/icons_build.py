"""Renders the Bob status icons (design/bob/icons/*.svg, Lucide, ISC) into antialiased A8 alpha masks
at the exact device glyph size and writes apps/cardputer/include/bob_icons.h.

The device tints each mask at draw time with a palette colour from the tokens and alpha-composites it
onto the status-arc disc (round_ui_chrome.cpp), so only the alpha channel is stored: one byte per pixel,
flash resident. Size and stroke width come from design/bob/tokens.json (statusArc.glyph), the same
values the demo page uses, so web and device draw the same icons at the same size.

  py -3.11 apps/cardputer/scripts/icons_build.py           write include/bob_icons.h
  py -3.11 apps/cardputer/scripts/icons_build.py --check   exit 1 if the header is stale
  py -3.11 apps/cardputer/scripts/icons_build.py --png out  also write a contact sheet (tinted on the disc)

Deterministic: resvg-py is pinned in design/bob/requirements.txt, no timestamps, LF endings.
"""
from __future__ import annotations

import io
import json
import re
import sys
from pathlib import Path

import resvg_py
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
TOKENS = json.loads((ROOT / "design/bob/tokens.json").read_text(encoding="utf-8"))
ICON_DIR = ROOT / "design/bob/icons"
DEMO_DIR = ROOT / "design/bob/icons-demo"  # the approved demo's drawn icons: they replace the Lucide file of the same name
OUT = ROOT / "apps/cardputer/include/bob_icons.h"

SIZE = TOKENS["statusArc"]["glyph"]["size"]
STROKE = TOKENS["statusArc"]["glyph"]["strokeWidth"]
SS = 8  # supersample factor: render big, box-filter down; pixel-exact and independent of the rasteriser's AA
HI = 2  # masks are stored at 2x so the device can rotate them with 2x2 supersampling, like the browser rotating a vector icon


def render_alpha(svg_text: str, demo: bool) -> bytes:
    svg = svg_text.replace("currentColor", "#ffffff")
    if not demo:
        svg = svg.replace('stroke-width="2"', f'stroke-width="{STROKE}"')
    out = SIZE * HI
    big = out * SS
    png = resvg_py.svg_to_bytes(svg_string=svg, width=big, height=big)
    img = Image.open(io.BytesIO(bytes(png))).convert("RGBA")
    alpha = img.getchannel("A").resize((out, out), Image.BOX)
    return alpha.tobytes()


def ident(name: str) -> str:
    return "kIcon" + "".join(p.capitalize() for p in re.split(r"[-_]", name))


def build() -> tuple[str, dict[str, bytes]]:
    demo = {p.stem for p in DEMO_DIR.glob("*.svg")}
    masks = {p.stem: render_alpha((DEMO_DIR / p.name if p.stem in demo else p).read_text(encoding="utf-8"), p.stem in demo) for p in sorted(ICON_DIR.glob("*.svg"))}
    lines = [
        "// GENERATED by apps/cardputer/scripts/icons_build.py from design/bob/icons/*.svg (Lucide, ISC) and design/bob/tokens.json.",
        "// Do not edit by hand. A8 alpha masks, row-major, kIconSize x kIconSize; tint and composite at draw time.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "namespace bob",
        "{",
        "namespace bobicons",
        "{",
        "",
        f"constexpr int16_t kIconSize = {SIZE * HI};  // mask side in 2x pixels; the icon draws {SIZE} px wide",
        "",
    ]
    for name, data in masks.items():
        lines.append(f"// {name}")
        lines.append(f"const uint8_t {ident(name)}[{SIZE * HI * SIZE * HI}] = {{")
        for r in range(SIZE * HI):
            row = data[r * SIZE * HI:(r + 1) * SIZE * HI]
            lines.append("    " + ", ".join(f"0x{b:02X}" for b in row) + ",")
        lines.append("};")
        lines.append("")
    lines += ["} // namespace bobicons", "} // namespace bob", ""]
    return "\n".join(lines), masks


def sheet(masks: dict[str, bytes], out: Path) -> None:
    disc = TOKENS["palette"]["chipDisc"]
    tint = TOKENS["palette"]["sky"]
    scale = 8
    cols = 5
    names = list(masks)
    rows = (len(names) + cols - 1) // cols
    cell = SIZE * HI * scale + 16
    sheet_img = Image.new("RGB", (cols * cell, rows * cell), TOKENS["palette"]["ink"])
    for i, n in enumerate(names):
        m = Image.frombytes("L", (SIZE * HI, SIZE * HI), masks[n]).resize((SIZE * HI * scale, SIZE * HI * scale), Image.NEAREST)
        tile = Image.new("RGB", m.size, disc)
        tile.paste(Image.new("RGB", m.size, tint), (0, 0), m)
        sheet_img.paste(tile, ((i % cols) * cell + 8, (i // cols) * cell + 8))
    out.mkdir(parents=True, exist_ok=True)
    sheet_img.save(out / "icons-sheet.png")


def main(argv: list[str]) -> int:
    text, masks = build()
    if "--check" in argv:
        have = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else None
        if have != text:
            print("stale: apps/cardputer/include/bob_icons.h (run icons_build.py and commit)", file=sys.stderr)
            return 1
        print("bob icons: bob_icons.h up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(masks)} icons, {SIZE * HI}x{SIZE * HI} A8)")
    if "--png" in argv:
        sheet(masks, Path(argv[argv.index("--png") + 1]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
