"""Nunito smooth fonts for the Waveshare round screen (src/round_fonts.cpp).

lib/fonts/Nunito[wght].ttf (OFL, licence in lib/fonts/OFL.txt)  ->  lib/fonts/nunito_<role>.vlw

Each role is rendered at one pixel size and variable weight, antialiased, and written as a
Processing VLW (the format M5GFX loadFont() reads: 24-byte big-endian header, 28-byte glyph
records sorted by code point, then 8-bit alpha bitmaps). Glyphs: printable ASCII plus the
symbols the UI draws. Output is deterministic for one Pillow/FreeType build.

  py -3.11 scripts/font_build.py          regenerate lib/fonts/*.vlw
  py -3.11 scripts/font_build.py --check  fail if a committed file differs
"""
from pathlib import Path
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "lib" / "fonts"
TTF = DIR / "Nunito[wght].ttf"

# role -> (pixel size, weight). SemiBold 600, ExtraBold 800.
ROLES = {
    "caption": (15, 600),
    "body": (17, 730),
    "title": (24, 800),
    "hero": (40, 800),
    "url": (14, 600),   # the pairing address line (the demo: 14 px)
    "micro": (12, 600),  # the pairing countdown (the demo: 12 px)
    "code": (32, 800),  # the pairing code (the demo: 36 px monospace, about this width in Nunito)
}
CODES = list(range(0x20, 0x7F)) + [0xB0, 0x2026]  # ASCII, degree sign, ellipsis


SS = 8  # supersampling: glyphs are drawn at 8x and box-filtered down, so outlines are unhinted like the browser render


def glyph(big: ImageFont.FreeTypeFont, code: int) -> tuple:
    ch = chr(code)
    advance = round(big.getlength(ch) / SS)
    left, top, right, bottom = big.getbbox(ch, anchor="ls")  # in 8x pixels, relative to the baseline origin
    if right <= left or bottom <= top:  # space
        return code, 0, 0, advance, 0, 0, b""
    l, t = left // SS, top // SS  # snap the bitmap box to whole output pixels
    r, btm = -(-right // SS), -(-bottom // SS)
    w, h = r - l, btm - t
    img = Image.new("L", (w * SS, h * SS), 0)
    ImageDraw.Draw(img).text((-l * SS, -t * SS), ch, font=big, fill=255, anchor="ls")
    img = img.resize((w, h), Image.BOX)
    # Browsers render text heavier than a plain coverage mask; a gentle gamma matches the approved demo.
    img = img.point(lambda v: round(255 * (v / 255) ** 0.85))
    return code, h, w, advance, -t, l, img.tobytes()


# The browser lays text out with fractional advances at the CSS weight (600 for the body role); the VLW stores integer
# advances, which drift from it by a pixel or two within a line. include/round_fonts_adv.h carries the body role's
# unhinted advances in 1/16 px (ASCII 0x20..0x7E) so the device can place each glyph where the browser does.
ADV_ROLE, ADV_WEIGHT = "body", 600


def adv_header() -> str:
    size = ROLES[ADV_ROLE][0]
    big = ImageFont.truetype(str(TTF), size * 16)
    big.set_variation_by_axes([ADV_WEIGHT])
    adv = [round(big.getlength(chr(c))) for c in range(0x20, 0x7F)]
    rows = [", ".join(str(v) for v in adv[i:i + 12]) for i in range(0, len(adv), 12)]
    nl = chr(10)
    lines = ["// GENERATED by scripts/font_build.py: unhinted advances of the body font at weight %d, in 1/16 px, ASCII 0x20..0x7E." % ADV_WEIGHT,
             "#pragma once", "#include <stdint.h>", "namespace bob", "{", "constexpr uint16_t kBodyAdv16[95] = {"]
    lines += ["  " + r + ("," if i < len(rows) - 1 else "") for i, r in enumerate(rows)]
    lines += ["};", "}", ""]
    return nl.join(lines)


def render(size: int, weight: int) -> bytes:
    font = ImageFont.truetype(str(TTF), size)
    font.set_variation_by_axes([weight])
    big = ImageFont.truetype(str(TTF), size * SS)
    big.set_variation_by_axes([weight])
    glyphs = [glyph(big, c) for c in CODES]
    ascent = -font.getbbox("d", anchor="ls")[1]
    descent = font.getbbox("p", anchor="ls")[3]
    out = bytearray(struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent))
    for code, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", code, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    return bytes(out)


def main() -> int:
    check = "--check" in sys.argv[1:]
    bad = 0
    for role, (size, weight) in ROLES.items():
        data = render(size, weight)
        path = DIR / f"nunito_{role}.vlw"
        if check:
            if not path.is_file() or path.read_bytes() != data:
                print(f"DIFFERS: {path.name}")
                bad += 1
        else:
            path.write_bytes(data)
            print(f"wrote {path.name} ({len(data)} B, {size} px, wght {weight})")
    adv_path = ROOT / "include" / "round_fonts_adv.h"
    adv = adv_header()
    if check:
        if not adv_path.is_file() or adv_path.read_text(encoding="utf-8") != adv:
            print(f"DIFFERS: {adv_path.name}")
            bad += 1
    else:
        adv_path.write_text(adv, encoding="utf-8", newline=chr(10))
        print(f"wrote {adv_path.name}")
    if check and not bad:
        print("fonts: ok")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
