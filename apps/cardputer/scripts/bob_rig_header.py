#!/usr/bin/env python3
"""Generate the firmware's rig tables from assets/bob/rig/rig.json.

  libs/bob-device/src/bob_rig_data.h     part sizes, pivots, per-pose placement (pure tables, host-testable)
  libs/bob-device/src/bob_rig_blobs.inc  the asm() block that .incbin's lib/bob_art/rig/*.rgb565a8 (bob_rig.cpp only)

Usage: py -3.11 apps/cardputer/scripts/bob_rig_header.py [--check]
  --check  regenerate in memory and exit 1 when the committed files differ.
The blobs themselves come from bob_rig_build.py --device-blobs.
"""
import json
import re
import sys
from pathlib import Path

APP = Path(__file__).resolve().parents[1]
RIG = json.loads((APP / "assets/bob/rig/rig.json").read_text())
# The visor glass outline the approved demo clips the eyes to (its inline rig table, written by bob_rig_build.py
# sync_demo from the visor art): visor-part px, so the device clips its eyes to the same polygon.
APPROVED_DEMO = APP.parents[1] / "docs/waveshare/golden/approved-demo.html"


def visor_clip() -> list:
    html = APPROVED_DEMO.read_text(encoding="utf-8")
    table = json.loads(html[html.index("/*RIG*/") + len("/*RIG*/"):html.index("/*END*/")])
    return [(float(x), float(y)) for x, y in re.findall(r"([-\d.]+) ([-\d.]+)", table["visorClip"])]
POSES = ["helper", "curious", "thoughtful", "playful"]  # BobPose order: welcome, curious, thoughtful, playful
parts = sorted(RIG["parts"].items(), key=lambda kv: kv[1]["z"])
names = [n for n, _ in parts]


def ident(n: str) -> str:
    ps = n.split("_")
    return "k" + ps[0][0].upper() + ps[0][1:] + "".join(p.capitalize() for p in ps[1:])


def f(v) -> str:
    return f"{float(v):.1f}f"


def data() -> str:
    o = ["// GENERATED by scripts/bob_rig_header.py from assets/bob/rig/rig.json. Do not edit.",
         "// Stage = the 197 px square the rig is cut on (device px, Bob about 192 px tall).",
         "#pragma once", "", "#include <stdint.h>", "", "namespace bob {", "namespace rig {", "",
         f"constexpr int kStage = {RIG['stage'][0]};",
         f"constexpr float kArtScale = {RIG['scale']}f;  // art px -> device px (the demo's S: its move and eye units)",
         "", "enum Part : uint8_t {"]
    o += [f"  {ident(n)}," for n in names] + [f"  kPartCount = {len(names)}", "};", ""]
    o += ["struct PartInfo {", "  const char* name;", "  uint16_t w, h;",
          "  float pivotX, pivotY;  // inside the part: ankle, shoulder, seam, base ...",
          "  bool front;            // drawn after the head (ear and chin arms)", "};", "",
          "constexpr PartInfo kParts[kPartCount] = {"]
    for n, p in parts:
        o.append(f'  {{"{n}", {p["w"]}, {p["h"]}, {f(p["pivot"][0])}, {f(p["pivot"][1])}, {"true" if p["front"] else "false"}}},')
    o += ["};", "",
          "// A shared part (foot, visor, button) registered onto a pose: rest rotation, scale and where its pivot lands on the stage.",
          "struct Placed {", "  float rot, scale, x, y;", "};", "",
          "struct PoseRig {", "  Part head;", "  float headX, headY;   // head origin on the stage",
          "  float seamX, seamY;   // head pivot (the neck seam), stage px",
          "  Part belly;", "  float bellyX, bellyY;", "  Placed footL, footR, visor, button;",
          "  Part armL, armR;      // the arms of the source art (rest arrangement)", "};", "",
          "constexpr PoseRig kPoses[4] = {"]
    for pose in POSES:
        e = RIG["poses"][pose]

        def pl(k, e=e):
            s = e["shared"][k]
            return f"{{{f(s['rot'])}, {f(s['scale'])}, {f(s['pivot_at'][0])}, {f(s['pivot_at'][1])}}}"

        arms = e["arms"]
        al = next(a for a in arms if a.startswith("armL"))
        ar = next(a for a in arms if a.startswith("armR"))
        o.append(f"  {{{ident(e['head']['part'])}, {f(e['head']['at'][0])}, {f(e['head']['at'][1])}, {f(e['head']['seam_pivot'][0])}, {f(e['head']['seam_pivot'][1])},")
        o.append(f"   {ident(e['belly']['part'])}, {f(e['belly']['at'][0])}, {f(e['belly']['at'][1])},")
        o.append(f"   {pl('footL')}, {pl('footR')}, {pl('visor')}, {pl('button')},")
        o.append(f"   {ident(al)}, {ident(ar)}}},  // {pose}")
    o += ["};", "", "// Where each arm variant's shoulder sits on the stage (its source pose); 0 for non-arm parts.",
          "struct Shoulder {", "  float x, y;", "};", "constexpr Shoulder kShoulders[kPartCount] = {"]
    sh = {}
    for pose in POSES:
        for a, v in RIG["poses"][pose]["arms"].items():
            sh[a] = v["shoulder"]
    for n in names:
        s = sh.get(n, [0, 0])
        o.append(f"  {{{f(s[0])}, {f(s[1])}}},  // {n}")
    # The rig box's left edge on the glass per pose, as the approved demo sets it (applyPlacement: the body centred on
    # x 180, written with toFixed(1)); Python's '.1f' rounds the same double the same way.
    lefts = []
    for pose in POSES:
        e = RIG["poses"][pose]
        hw, bw = RIG["parts"][e["head"]["part"]]["w"], RIG["parts"][e["belly"]["part"]]["w"]
        body_cx = ((e["head"]["at"][0] + hw / 2) + (e["belly"]["at"][0] + bw / 2)) / 2
        lefts.append(float(f"{81.5 + 98.5 - body_cx:.1f}"))
    o += ["};", "", "// The rig box's left edge on the glass per pose, exactly as the demo writes it (toFixed(1) of 180 - body centre).",
          "constexpr float kPoseRigLeft[4] = {" + ", ".join(f(v) for v in lefts) + "};"]
    clip = visor_clip()
    o += ["", "// The visor glass outline (visor-part px) the eyes are clipped to: the approved demo's visorClip polygon.",
          "struct ClipPt {", "  float x, y;", "};", f"constexpr int kVisorClipN = {len(clip)};",
          "constexpr ClipPt kVisorClip[kVisorClipN] = {"]
    o += ["  " + " ".join(f"{{{f(x)}, {f(y)}}}," for x, y in clip[i:i + 6]) for i in range(0, len(clip), 6)]
    o += ["};", "", "}  // namespace rig", "}  // namespace bob", ""]
    return "\n".join(o)


def blobs() -> str:
    o = ["// GENERATED by scripts/bob_rig_header.py. Included only by bob_rig.cpp.",
         "// The blobs are RGB565 (little endian) then A8, w*h each; the build adds -Wa,-I$PROJECT_DIR/lib/bob_art/rig.",
         'asm(".section .rodata.bob_rig,\\"a\\"\\n"']
    for n in names:
        o += ['    ".balign 4\\n"', f'    ".global bob_rig_{n}\\n"', f'    "bob_rig_{n}:\\n"',
              f'    ".incbin \\"{n}.rgb565a8\\"\\n"']
    o += ['    ".previous\\n");']
    o += [f'extern "C" const uint8_t bob_rig_{n}[];' for n in names]
    o += ["", "namespace bob {", "namespace rig {", "namespace {", "const uint8_t* const kBlobs[kPartCount] = {"]
    o += [f"    bob_rig_{n}," for n in names]
    o += ["};", "}  // namespace", "}  // namespace rig", "}  // namespace bob", ""]
    return "\n".join(o)


# Bob's portable core (libs/bob-device, ADR 0004) holds the generated tables; the blobs stay in this app's lib/bob_art/rig.
LIB = APP.parents[1] / "libs/bob-device/src"
out = {LIB / "bob_rig_data.h": data(), LIB / "bob_rig_blobs.inc": blobs()}
if "--check" in sys.argv:
    bad = [str(p) for p, t in out.items() if not p.exists() or p.read_text() != t.replace("\r\n", "\n")]
    print("drift: " + ", ".join(bad) if bad else "rig tables up to date")
    sys.exit(1 if bad else 0)
for p, t in out.items():
    p.write_text(t, newline="\n")
    print("wrote", p.relative_to(APP.parents[1]))
