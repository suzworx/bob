// Bob design-system generator: design/bob/tokens.json (+ design/bob/icons/*.svg) -> every consumer file.
//   node design/bob/build.mjs           write the outputs
//   node design/bob/build.mjs --check   fail (exit 1) if any output differs from what the tokens generate
// Deterministic: no timestamps, stable key order, LF line endings.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const T = JSON.parse(readFileSync(join(root, 'design/bob/tokens.json'), 'utf8'));
const check = process.argv.includes('--check');
const BANNER = 'GENERATED by design/bob/build.mjs from design/bob/tokens.json. Do not edit by hand.';

const rgb = (hex) => parseInt(hex.slice(1), 16);
const hex6 = (hex) => '0x' + hex.slice(1).toUpperCase();
const kName = (s) => 'k' + s.replace(/(^|[-_ ])(\w)/g, (_, __, c) => c.toUpperCase());
const fl = (n) => (Number.isInteger(n) ? `${n}.0f` : `${n}f`);

// ---- icons: inner SVG markup of every file in design/bob/icons (24x24, stroke currentColor) ----
const iconDir = join(root, 'design/bob/icons');
const icons = {};
for (const f of readdirSync(iconDir).filter((n) => n.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(iconDir, f), 'utf8').replace(/\r/g, '');
  const m = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  icons[f.replace(/\.svg$/, '')] = m[1].split('\n').map((l) => l.trim()).filter(Boolean).join('');
}

const P = T.palette, G = T.grid, A = T.statusArc, R = T.ring, C = T.chips, M = T.motion, Y = T.typography.roles;

// ---- CSS custom properties for the demo page ----
const css = [];
css.push(`/* ${BANNER} */`, ':root {');
for (const [k, v] of Object.entries(P)) css.push(`  --${k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}: ${v};`);
css.push(`  --ease: cubic-bezier(${M.ease.join(', ')});`);
css.push(`  --bob-font: "${T.typography.family}", ${T.typography.fallback};`);
for (const [k, v] of Object.entries(Y)) {
  css.push(`  --bob-${k}-size: ${v.size}px;`, `  --bob-${k}-weight: ${v.weight};`);
}
css.push(`  --bob-size: ${G.size}px;`, `  --bob-caption-y: ${G.caption.y}px;`);
css.push(`  --bob-cx: ${G.bob.cx}px;`, `  --bob-cy: ${G.bob.cy}px;`, `  --bob-feet-y: ${G.bob.feetY}px;`);
css.push(`  --arc-radius: ${A.radius}px;`, `  --arc-step: ${A.stepDeg}deg;`);
css.push(`  --chip-disc-size: ${A.disc.diameter}px;`, `  --chip-disc-color: ${P[A.disc.color]};`);
css.push(`  --glyph-size: ${A.glyph.size}px;`, `  --glyph-stroke: ${A.glyph.strokeWidth};`);
css.push(`  --ring-w: ${R.outer - R.inner}px;`, `  --ring-speak-min: ${R.speakMinWidth}px;`, `  --ring-speak-span: ${R.speakMaxWidth - R.speakMinWidth}px;`);
css.push(`  --gesture-ms: ${M.gestureMs}ms;`, `  --settle-ms: ${M.settleMs}ms;`, `  --fade-ms: ${M.fadeMs}ms;`);
for (const [k, v] of Object.entries(M.ringMs)) css.push(`  --ring-${k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}-ms: ${v}ms;`);
css.push(`  --reply-top: ${T.reply.textTop}px;`, `  --reply-h: ${T.reply.textHeight}px;`, `  --reply-inset: ${T.reply.textInset}px;`, `  --reply-dots-y: ${T.reply.dotsY}px;`);
css.push('}', '');

// ---- JS data for the demo page (arc geometry, states, inline icon markup) ----
const js = `/* ${BANNER} */\nwindow.BOB = ${JSON.stringify({ ...T, icons }, null, 1)};\n`;

// ---- C++11 header for the firmware ----
const h = [];
h.push(`// ${BANNER}`, '// Change design/bob/tokens.json, then run `node design/bob/build.mjs`.', '#pragma once', '', '#include <stdint.h>', '', 'namespace bob', '{', 'namespace bobtok', '{', '');
h.push('// Palette, RGB888.');
for (const [k, v] of Object.entries(P)) h.push(`constexpr uint32_t ${kName(k)} = ${hex6(v)};`);
h.push('', '// Typography: Nunito role sizes (px) and weights.');
for (const [k, v] of Object.entries(Y)) h.push(`constexpr int16_t ${kName(k)}Size = ${v.size};`, `constexpr int16_t ${kName(k)}Weight = ${v.weight};`);
h.push('', '// Placement grid on the 360 circle.');
h.push(`constexpr int16_t kSize = ${G.size}, kCenter = ${G.center}, kRadius = ${G.radius}, kMargin = ${G.margin};`);
h.push(`constexpr int16_t kBobCx = ${G.bob.cx}, kBobCy = ${G.bob.cy}, kBobFeetY = ${G.bob.feetY};`);
h.push(`constexpr int16_t kBobClipTop = ${G.bob.clipTop}, kBobClipBottom = ${G.bob.clipBottom};`);
h.push(`constexpr int16_t kBobFrameH = ${G.bob.frameH}; // rows of the frame sprite, from kBobFrameTop`);
h.push(`constexpr int16_t kBobFrameTop = ${G.bob.frameTop}; // top row of Bob's frame sprite (the accents are drawn in it); the clip may start lower, under the status discs`);
h.push(`constexpr int16_t kPropLeftX = ${G.propSlots.left[0]}, kPropLeftY = ${G.propSlots.left[1]};`);
h.push(`constexpr int16_t kPropRightX = ${G.propSlots.right[0]}, kPropRightY = ${G.propSlots.right[1]};`);
h.push(`constexpr int16_t kCaptionY = ${G.caption.y};`);
h.push(`constexpr int16_t kBodyTop = ${G.body.top}, kBodyBottom = ${G.body.bottom};`);
h.push('', '// Status arc: N icons at (i - (N-1)/2) * kArcStepDeg about 12 o\'clock on radius kArcRadius.');
h.push(`constexpr int16_t kArcRadius = ${A.radius}, kDiscDiameter = ${A.disc.diameter}, kGlyphSize = ${A.glyph.size};`);
h.push(`constexpr float kArcStepDeg = ${fl(A.stepDeg)};`);
h.push(`constexpr uint32_t kDiscColor = ${hex6(P[A.disc.color])};`);
h.push('', '// Ring annulus radii (px from the centre).');
h.push(`constexpr float kRingInner = ${fl(R.inner)}, kRingCoreIn = ${fl(R.coreIn)}, kRingCoreOut = ${fl(R.coreOut)}, kRingOuter = ${fl(R.outer)};`);
h.push('', '// Shortcut chip strip.');
h.push(`constexpr int16_t kChipRowX = ${C.rowX}, kChipRowW = ${C.rowW}, kChipRowY = ${C.rowY}, kChipRowH = ${C.rowH}, kChipRow1Dy = ${C.row1Dy}, kChipStripH = ${C.stripH};`);
h.push(`constexpr int16_t kChipAvail0 = ${C.avail[0]}, kChipAvail1 = ${C.avail[1]}, kChipGap = ${C.gap}, kChipRadius = ${C.radius};`);
h.push(`constexpr uint32_t kChipOverlayMs = ${C.overlayMs}, kChipPageMs = ${C.pageMs}, kChipShownMs = ${C.shownMs};`);
h.push(`constexpr uint32_t kChipBg = ${hex6(P[C.bg])}, kChipBgHot = ${hex6(P[C.bgHot])};`);
h.push('', '// Motion.');
h.push(`constexpr uint32_t kGestureMs = ${M.gestureMs}, kSettleMs = ${M.settleMs}, kFadeMs = ${M.fadeMs}, kLinkPulseMs = ${M.linkPulseMs};`);
h.push(`constexpr float kEaseX1 = ${fl(M.ease[0])}, kEaseY1 = ${fl(M.ease[1])}, kEaseX2 = ${fl(M.ease[2])}, kEaseY2 = ${fl(M.ease[3])};`);
h.push(`constexpr float kSpringFreq = ${fl(M.spring.freq)}, kSpringDamping = ${fl(M.spring.damping)};`);
h.push('', '// The one caption line under Bob, per state (empty states omitted).');
for (const [k, v] of Object.entries(T.states)) if (v.caption) h.push(`constexpr const char* kCaption${k[0].toUpperCase()}${k.slice(1)} = ${JSON.stringify(v.caption)};`);
h.push('', '// What the round screen says during and after a turn: the reply page turn and the kind error caption, in ms.');
h.push(`constexpr uint32_t kReplyPageMs = ${T.feedback.replyPageMs}, kTroubleMs = ${T.feedback.troubleMs};`);
h.push('', '// The reply card: the text block (centred in textTop..textTop+textHeight, one line per row of 24 px), the page dots.');
h.push(`constexpr int16_t kReplyTextTop = ${T.reply.textTop}, kReplyTextHeight = ${T.reply.textHeight}, kReplyTextInset = ${T.reply.textInset}, kReplyDotsY = ${T.reply.dotsY}, kReplyDotSize = ${T.reply.dotSize}, kReplyDotGap = ${T.reply.dotGap}, kReplyLines = ${T.reply.lines};`);
h.push('', '// Bob smaller and higher in a state (scale about the feet line, then a rise in px; absent states keep 1 and 0).');
for (const [k, v] of Object.entries(T.states)) if (v.bob) h.push(`constexpr float kBobScale${k[0].toUpperCase()}${k.slice(1)} = ${fl(v.bob.scale)}, kBobRise${k[0].toUpperCase()}${k.slice(1)} = ${fl(v.bob.rise)};`);
h.push('', '} // namespace bobtok', '} // namespace bob', '');

// ---- JSON for the placement checker ----
const checker = {
  _generated: BANNER,
  screen: G.size,
  center: [G.center, G.center],
  bodyCenter: [G.bob.cx, G.bob.cy],
  feetY: G.bob.feetY,
  topGapMin: G.bob.topGapMin,
  ringInner: R.inner,
  ringOuter: R.outer,
  statusArc: { radius: A.radius, stepDeg: A.stepDeg, discDiameter: A.disc.diameter, glyph: A.glyph.size },
  captionY: G.caption.y,
  margin: G.margin,
  ink: P.ink,
  chipDisc: P.chipDisc,
};

const outputs = {
  'docs/waveshare/bob-tokens.css': css.join('\n'),
  'docs/waveshare/bob-tokens.js': js,
  'libs/bob-device/src/bob_tokens.h': h.join('\n'),
  'apps/cardputer/scripts/bob_tokens.json': JSON.stringify(checker, null, 2) + '\n',
};

let stale = 0;
for (const [path, body] of Object.entries(outputs)) {
  const file = join(root, path);
  const have = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
  if (check) {
    if (have !== body) { console.error(`stale: ${path}`); stale++; }
  } else {
    writeFileSync(file, body);
    console.log(`wrote ${relative(root, file)}`);
  }
}
if (check) {
  if (stale) { console.error('run `node design/bob/build.mjs` and commit the result'); process.exit(1); }
  console.log('bob tokens: all outputs up to date');
}
