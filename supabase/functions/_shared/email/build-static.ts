/**
 * Generates supabase/templates/*.html, the Supabase Auth fallback templates
 * named in supabase/config.toml, from the catalog. They are used only when the
 * Send Email Hook is off (and locally, in Mailpit), and must look identical to
 * the hook's mail, so each is the matching catalog template rendered by
 * renderEmail with Supabase's Go-template placeholders as its data.
 *
 *   deno run --allow-read --allow-write supabase/functions/_shared/email/build-static.ts          # write
 *   deno run --allow-read --allow-write supabase/functions/_shared/email/build-static.ts --check  # exit 1 on drift
 */
import { findTemplate } from "./catalog.ts";
import { renderEmail } from "./render.ts";

/** Supabase's template variables, and the sentinel each is rendered as. */
const PLACEHOLDERS = {
  // A URL placeholder renders through a safe https sentinel, or renderEmail
  // would refuse it as a link and print it as text.
  confirmationUrl: { sentinel: "https://bob.invalid/BOBPH_CONFIRMATION_URL", value: "{{ .ConfirmationURL }}" },
  token: { sentinel: "BOBPH_TOKEN", value: "{{ .Token }}" },
  newEmail: { sentinel: "BOBPH_NEW_EMAIL", value: "{{ .NewEmail }}" },
  email: { sentinel: "BOBPH_EMAIL", value: "{{ .Email }}" },
  provider: { sentinel: "BOBPH_PROVIDER", value: "{{ .Provider }}" },
  factorType: { sentinel: "BOBPH_FACTOR_TYPE", value: "{{ .FactorType }}" },
} as const;

const P = Object.fromEntries(
  Object.entries(PLACEHOLDERS).map(([key, p]) => [key, p.sentinel]),
) as { [K in keyof typeof PLACEHOLDERS]: string };

/** config.toml's template file (without .html), the catalog id it is built from, and that template's data. */
export const STATIC_TEMPLATES: ReadonlyArray<{ file: string; id: string; data: Record<string, string> }> = [
  { file: "invite", id: "auth-account-invite", data: { acceptUrl: P.confirmationUrl, code: P.token } },
  { file: "confirmation", id: "auth-signup-confirm", data: { code: P.token, confirmUrl: P.confirmationUrl } },
  // The sign-in form asks for a code, so magic_link is the CODE email: no ConfirmationURL.
  { file: "magic_link", id: "auth-sign-in-code", data: { code: P.token } },
  { file: "recovery", id: "auth-password-reset", data: { resetUrl: P.confirmationUrl, code: P.token } },
  { file: "email_change", id: "auth-email-change-current", data: { code: P.token, newEmail: P.newEmail } },
  { file: "reauthentication", id: "auth-reauthenticate", data: { code: P.token } },
  { file: "password_changed_notification", id: "security-password-changed", data: {} },
  // In this notification {{ .Email }} is the new address ({{ .OldEmail }} the old one).
  { file: "email_changed_notification", id: "security-email-changed", data: { newEmail: P.email } },
  { file: "phone_changed_notification", id: "security-phone-changed", data: {} },
  { file: "identity_linked_notification", id: "security-identity-linked", data: { provider: P.provider } },
  { file: "identity_unlinked_notification", id: "security-identity-unlinked", data: { provider: P.provider } },
  { file: "mfa_factor_enrolled_notification", id: "security-mfa-enrolled", data: { factorType: P.factorType } },
  { file: "mfa_factor_unenrolled_notification", id: "security-mfa-unenrolled", data: { factorType: P.factorType } },
];

/** Render one static template, then put the exact Go-template placeholders back where the sentinels landed. */
function buildStaticHtml(file: string, id: string, data: Record<string, string>): string {
  const template = findTemplate(id);
  if (!template) throw new Error(`build-static: no catalog template ${id}`);
  let html = renderEmail(template.build(data)).html;
  // Longest sentinel first, so a sentinel that prefixes another never splits it.
  const ordered = Object.values(PLACEHOLDERS).sort((a, b) => b.sentinel.length - a.sentinel.length);
  for (const { sentinel, value } of ordered) html = html.split(sentinel).join(value);
  if (html.includes("BOBPH_")) throw new Error(`build-static: ${file} kept an unrestored placeholder`);
  const header = `<!-- Generated by build-static.ts — do not edit. Supabase Auth fallback template, built from ${id}. -->\n`;
  const doctype = "<!DOCTYPE html>\n";
  if (!html.startsWith(doctype)) throw new Error("build-static: rendered HTML must start with a doctype");
  return doctype + header + html.slice(doctype.length);
}

/** Every static file as [file name, contents]. */
export function buildStatic(): Array<[string, string]> {
  return STATIC_TEMPLATES.map(({ file, id, data }) => [`${file}.html`, buildStaticHtml(file, id, data)]);
}

async function main(): Promise<void> {
  const check = Deno.args.includes("--check");
  const dir = new URL("../../../templates/", import.meta.url);
  const drifted: string[] = [];
  for (const [name, html] of buildStatic()) {
    const path = new URL(name, dir);
    let current: string | undefined;
    try {
      current = await Deno.readTextFile(path);
    } catch {
      current = undefined;
    }
    if (current === html) continue;
    drifted.push(name);
    if (!check) await Deno.writeTextFile(path, html);
  }
  if (check && drifted.length > 0) {
    console.error(`supabase/templates out of date: ${drifted.join(", ")}`);
    console.error("Run: deno run --allow-read --allow-write supabase/functions/_shared/email/build-static.ts");
    Deno.exit(1);
  }
  console.log(check ? "supabase/templates up to date" : `wrote ${drifted.length} of ${STATIC_TEMPLATES.length} templates`);
}

if (import.meta.main) await main();
