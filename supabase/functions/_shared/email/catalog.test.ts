import { assert, assertEquals, assertStringIncludes, assertThrows } from "jsr:@std/assert@1";
import { assertCatalog, CATEGORIES, findTemplate, TEMPLATES } from "./catalog.ts";
import { buildStatic, STATIC_TEMPLATES } from "./build-static.ts";
import { renderEmail } from "./render.ts";

Deno.test("the catalog holds every template once, with a kebab-case id", () => {
  assertEquals(TEMPLATES.length, 37);
  const ids = TEMPLATES.map((t) => t.id);
  assertEquals(new Set(ids).size, ids.length);
  for (const id of ids) assert(/^[a-z0-9]+(-[a-z0-9]+)*$/.test(id), id);
  for (const t of TEMPLATES) assertEquals(findTemplate(t.id), t);
  assertEquals(findTemplate("no-such-template"), undefined);
  assertEquals(findTemplate("bob-message")?.category, "activity");
});

Deno.test("every template builds and renders from its sample, which has every required key", () => {
  for (const t of TEMPLATES) {
    assert(CATEGORIES.includes(t.category), t.id);
    assert(t.trigger.trim().length > 0, t.id);
    for (const key of t.required) assert(key in t.sample, `${t.id}: ${key}`);
    const rendered = renderEmail(t.build(t.sample));
    assert(rendered.subject.length > 0, t.id);
    assertStringIncludes(rendered.html, "<!DOCTYPE html>");
    assert(rendered.text.length > 0, t.id);
  }
});

Deno.test("assertCatalog rejects each kind of defect", () => {
  const good = TEMPLATES[0];
  assertThrows(() => assertCatalog([good, good]), Error, "duplicate id");
  assertThrows(() => assertCatalog([{ ...good, id: "Not_Kebab" }]), Error, "kebab-case");
  assertThrows(() => assertCatalog([{ ...good, category: "nope" as never }]), Error, "unknown category");
  assertThrows(() => assertCatalog([{ ...good, required: ["absent"] }]), Error, "lacks required key");
});

Deno.test("notify-email's refused prefixes cover exactly the auth, security and waitlist categories", async () => {
  const source = await Deno.readTextFile(new URL("../../notify-email/handler.ts", import.meta.url));
  const match = source.match(/REFUSED_PREFIXES = \[([^\]]*)\]/);
  assert(match, "REFUSED_PREFIXES not found in notify-email/handler.ts");
  const prefixes = [...match[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  assertEquals(prefixes.sort(), ["auth-", "security-", "waitlist-"]);
  for (const t of TEMPLATES) {
    const refused = prefixes.some((p) => t.id.startsWith(p));
    const internal = ["auth", "security", "waitlist"].includes(t.category);
    assertEquals(refused, internal, t.id);
  }
});

Deno.test("static templates: one per config.toml entry, placeholders survive rendering literally", async () => {
  const config = await Deno.readTextFile(new URL("../../../config.toml", import.meta.url));
  const named = [...config.matchAll(/content_path = "\.\/supabase\/templates\/([a-z_]+)\.html"/g)].map((m) => m[1]);
  assertEquals([...new Set(named)].sort(), STATIC_TEMPLATES.map((s) => s.file).sort());

  const files = new Map(buildStatic());
  assertEquals(files.size, 13);
  for (const [name, html] of files) {
    assertStringIncludes(html, "Generated by build-static.ts — do not edit");
    assert(!html.includes("BOBPH_"), name);
    assert(!html.includes("bob.invalid"), name);
  }
  const magic = files.get("magic_link.html")!;
  assertStringIncludes(magic, "{{ .Token }}");
  assert(!magic.includes("ConfirmationURL"), "magic_link must be the code email");
  assertStringIncludes(files.get("invite.html")!, 'href="{{ .ConfirmationURL }}"');
  assertStringIncludes(files.get("recovery.html")!, 'href="{{ .ConfirmationURL }}"');
  assertStringIncludes(files.get("confirmation.html")!, 'href="{{ .ConfirmationURL }}"');
  assertStringIncludes(files.get("email_change.html")!, "{{ .NewEmail }}");
  assertStringIncludes(files.get("email_changed_notification.html")!, "{{ .Email }}");
  assertStringIncludes(files.get("identity_linked_notification.html")!, "{{ .Provider }}");
  assertStringIncludes(files.get("mfa_factor_enrolled_notification.html")!, "{{ .FactorType }}");
});
