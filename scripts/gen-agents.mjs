import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

import { parse, stringify } from 'yaml';
import { CONTRACT as NATIVE_CONTRACT } from './agent-generation/contract.mjs';

/*
 * gen-agents.mjs — render one Claude Code subagent per domain in
 * .claude/domains.json, plus the role agents templated in scripts/agent-roles/.
 *
 * Every rendered file carries MARKER as its first body line; a file in the
 * target without it is hand-written and is never overwritten. The render
 * functions are pure and exported for the scripts Vitest suite and for
 * check-agents.mjs; the CLI runs only when this file is the entry point.
 *
 *   (no flag)    write every agent into .claude/agents/ (the lead runs this)
 *   --check      write nothing; exit 1 listing each file missing or different
 *   --dry        write nothing; print what would be written
 *   --out <dir>  use another target directory
 */

const ROOT = resolve(import.meta.dirname, '..');
const MANIFEST = '.claude/domains.json';
const ROLES_DIR = resolve(ROOT, 'scripts/agent-roles');
const AGENTS_DIR = resolve(ROOT, '.claude/agents');
const MODEL = 'inherit';
const TELLING_PATHS = 4;
const REFS = '.claude/skills/bob-dev/references';
export const MARKER = '<!-- generated by scripts/gen-agents.mjs from .claude/domains.json; edit the manifest, not this file -->';
const CONTRACT = `## Contract\n\nRead [${REFS}/agent-contract.md](../skills/bob-dev/references/agent-contract.md) and follow it exactly within the runtime adaptations below.\n\n${NATIVE_CONTRACT}`;
// The hard rule for apps/ui-v2, condensed from apps/ui-v2/CLAUDE.md (the source; read it in full).
const ASTRYX = [
  '- Astryx (`@astryxdesign/core`, pinned 0.6.2) is the only source of UI. No hand-written markup, spacing or',
  '  styling: no `className`, no `style={{}}`, no CSS beyond `src/base.css`. Never run `astryx swizzle`.',
  '- Before any UI code, from `apps/ui-v2`: `npm run astryx -- template --list`, then',
  '  `npm run astryx -- template <name> --skeleton`, then `npm run astryx -- component <Name>` for every component',
  '  used. Run `npm run astryx -- docs layout` and `npm run astryx -- docs spacing` before any frame or padding',
  '  decision. When the Astryx MCP and the CLI disagree, the CLI wins.',
  '- One frame: `Layout contentWidth={PAGE_WIDTH}` (`src/app/page-width.ts`). Icons are lucide through Astryx',
  '  `<Icon>`. Extend a component with a prop instead of forking it: one chat surface, one composer.',
  '- Astryx design and UX patterns decide which components go together, not just the component list.',
  '- Before building a screen, when `docs/ui-v2/ux-catalog/` exists: find the screen in its `mapping.json` and use',
  '  the Astryx template mapped there and the components `registry.json` lists. Follow the catalog\'s findings and',
  '  its "adopt next" modules instead of inventing. A screen with no mapping gets one in `mapping.json`.',
  '- After the change, when `check:ui-catalog` is in package.json: run `npm run ui:catalog:registry`, then',
  '  `npm run check:ui-catalog`. For evidence, `npm run ui:catalog` (with `npm run dev:offline -- --stub-ai`',
  '  running) renders the changed page at 1440 and 375 px next to its template, before and after.',
  '- Evidence is positive: in EVIDENCE, list the astryx commands you ran and attach a screenshot path of the',
  '  changed page, light and dark, from the e2e or the running app; a grep for CSS is not evidence.',
];
const HARDWARE = `- \`${REFS}/shared-hardware.md\`: check who holds COM3 and :7444 first.`;

const list = (items) => items.map((item) => `- \`${item}\``);
const section = (heading, lines) => [`## ${heading}`, '', ...lines, ''];

export function renderAgent(domain) {
  const name = `bob-${domain.name}`;
  const telling = domain.owns.slice(0, TELLING_PATHS).join(', ');
  const meta = {
    name,
    description: `${domain.summary} Owns ${telling}. Use for any change inside those paths; shared seams go to bob-platform.`,
    model: MODEL,
    skills: domain.skills,
    ...(domain.mcp.length > 0 ? { mcpServers: domain.mcp } : {}),
  };
  const ui = domain.owns.some((glob) => glob.startsWith('apps/ui-v2/'));
  const readFirst = [
    ...list(domain.docs),
    ...(ui ? ['- `apps/ui-v2/CLAUDE.md`, in full: the source of "UI: Astryx only".'] : []),
    ...(domain.owns.some((glob) => glob.startsWith('apps/cardputer/')) ? [HARDWARE] : []),
  ];
  return [
    '---', stringify(meta, { lineWidth: 0 }).trimEnd(), '---', MARKER,
    `# ${name}`, '', domain.summary, '',
    ...section('You own', list(domain.owns)),
    ...(ui ? section('UI: Astryx only', ASTRYX) : []),
    ...section('Your tests', list(domain.tests)),
    ...section('Read first', readFirst),
    ...section('Gates you must run', list(domain.gates)),
  ].join('\n') + `\n${CONTRACT}`;
}

export function renderRole(templateText) {
  const text = templateText.replace(/\r\n/g, '\n');
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
  if (!match) throw new Error('Missing role frontmatter');
  const meta = parse(match[1]);
  meta.model = MODEL;
  const rest = match[2].replace(/^\n+/, '');
  const withMarker = `---\n${stringify(meta, { lineWidth: 0 }).trimEnd()}\n---\n${MARKER}\n${rest}`;
  return withMarker.includes('## Bob native agent contract') ? withMarker : `${withMarker.trimEnd()}\n\n${CONTRACT}`;
}

// Map of file name (relative to the agents directory) -> rendered text.
export function renderAll(manifest, rolesDir = ROLES_DIR) {
  const files = new Map(manifest.domains.map((domain) => [`bob-${domain.name}.md`, renderAgent(domain)]));
  for (const file of readdirSync(rolesDir).filter((name) => name.endsWith('.md')).sort()) {
    files.set(file, renderRole(readFileSync(join(rolesDir, file), 'utf8')));
  }
  return files;
}

// One "file: reason" line per rendered file that is missing or differs in dir.
export function diffAgents(files, dir) {
  const differences = [...files].flatMap(([file, text]) => {
    const path = join(dir, file);
    if (!existsSync(path)) return [`${file}: missing`];
    return readFileSync(path, 'utf8') === text ? [] : [`${file}: differs from what scripts/gen-agents.mjs renders`];
  });
  if (existsSync(dir)) {
    for (const file of readdirSync(dir).filter((name) => name.endsWith('.md'))) {
      if (!files.has(file) && readFileSync(join(dir, file), 'utf8').includes(`\n${MARKER}\n`)) {
        differences.push(`${file}: stale generated agent (review removal manually)`);
      }
    }
  }
  return differences;
}

// Writes every rendered file except those hand-written (no MARKER) in dir.
export function writeAgents(files, dir) {
  mkdirSync(dir, { recursive: true });
  const written = [];
  const kept = [];
  for (const [file, text] of files) {
    if (basename(file) !== file) throw new Error(`Invalid output filename: ${file}`);
    const path = join(dir, file);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined;
    if (current !== undefined && !current.includes(`\n${MARKER}\n`)) kept.push(file);
    else if (current !== text) {
      writeFileSync(path, text);
      written.push(file);
    }
  }
  return { written, kept };
}

const isDirectRun = Boolean(process.argv[1]) &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href;

if (isDirectRun) {
  const args = process.argv.slice(2);
  const outAt = args.indexOf('--out');
  const dir = outAt >= 0 ? resolve(args[outAt + 1]) : AGENTS_DIR;
  const files = renderAll(JSON.parse(readFileSync(resolve(ROOT, MANIFEST), 'utf8')));
  if (args.includes('--check')) {
    const problems = diffAgents(files, dir);
    for (const problem of problems) console.error(problem);
    if (problems.length > 0) process.exit(1);
    console.log(`agents: ${files.size} up to date`);
  } else if (args.includes('--dry')) {
    console.log(`would write ${files.size} agents`);
    for (const file of files.keys()) console.log(`  ${join(dir, file)}`);
  } else {
    const { written, kept } = writeAgents(files, dir);
    for (const file of kept) console.log(`kept ${file} (hand-written, no generated marker)`);
    console.log(`wrote ${written.length} agents into ${dir}`);
  }
}
